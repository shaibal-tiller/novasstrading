// Lists the pictures that ship inside the website (public/assets) so the editor's media picker can offer them
// next to uploaded files. Run after adding or removing pictures there:  node scripts/make-bundled-photos.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = join(process.cwd(), "public", "assets");
const GROUPS = {
  "products/women": "Women",
  "products/men": "Men",
  "products/kids": "Kids",
  "products/lingerie": "Lingerie",
  "products/categories": "Product ranges",
  logos: "Logos",
};

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}

const rows = walk(ROOT)
  .map((f) => relative(ROOT, f).split("\\").join("/"))
  .filter((p) => /\.(jpe?g|png|webp)$/i.test(p))
  .sort()
  .map((path) => {
    const dir = path.split("/").slice(0, -1).join("/");
    return { path, group: GROUPS[dir] ?? "Other" };
  });

const out = `// GENERATED by scripts/make-bundled-photos.mjs — do not edit by hand.
export type BundledPhoto = { path: string; group: string };

export const BUNDLED_PHOTOS: BundledPhoto[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(process.cwd(), "lib", "admin", "bundled-photos.generated.ts"), out);
console.log(`${rows.length} pictures listed`);
